"""Build a static Cloudflare Pages directory without embedded image data.

Run: python3 scripts/build-cloudflare.py
The output directory contains only index.html, CSS, JavaScript and assets.
The portable single-file index.html at the repository root is left untouched.
"""

from pathlib import Path
import argparse
import re
import shutil
import tempfile

ROOT = Path(__file__).resolve().parent.parent
MAX_FILE_BYTES = 25 * 1024 * 1024


def build(destination: Path) -> None:
    destination = destination.resolve()
    # Never replace the source repository or one of its parent directories.
    if destination == ROOT or destination in ROOT.parents:
        raise ValueError("Choose a separate output directory, not the source repository.")
    if destination.exists() and not (destination / ".greenstoa-pages-build").is_file():
        raise ValueError(f"Refusing to replace an unmarked directory: {destination}")

    page = (ROOT / "templates/index.html").read_text(encoding="utf-8")
    css = re.findall(r'<link rel="stylesheet" href="(CSS/[^"]+)"', page)
    scripts = re.findall(r'<script src="(JS/[^"]+)"', page)
    if not css or not scripts or "data:image/" in page:
        raise ValueError("Expected the source template with external styles, scripts and images.")

    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="greenstoa-pages-", dir=destination.parent) as temp:
        staging = Path(temp)
        (staging / "index.html").write_text(page, encoding="utf-8")
        for name in css + scripts:
            target = staging / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ROOT / name, target)
        # Keep all game assets and their font licenses, including assets used in later scenes.
        shutil.copytree(ROOT / "assets", staging / "assets")
        (staging / "_headers").write_text(
            "/*\n  X-Content-Type-Options: nosniff\n\n"
            "/index.html\n  Cache-Control: public, max-age=0, must-revalidate\n", encoding="utf-8"
        )
        files = [path for path in staging.rglob("*") if path.is_file()]
        oversized = [path.relative_to(staging) for path in files if path.stat().st_size >= MAX_FILE_BYTES]
        if oversized:
            raise ValueError(f"Files exceed the Pages limit: {oversized}")
        largest = max(files, key=lambda path: path.stat().st_size)
        report = (
            "Cloudflare Pages 배포용 그린스토아\n\n"
            "직접 업로드: ZIP을 풀고 이 폴더를 Cloudflare Pages의 자산 업로드 화면에 올립니다.\n"
            "index.html과 CSS, JS, assets 폴더를 모두 함께 올려야 합니다.\n"
            "원본 저장소의 대용량 통합 index.html을 섞지 마세요.\n\n"
            f"index.html: {(staging / 'index.html').stat().st_size:,} bytes\n"
            f"가장 큰 파일: {largest.relative_to(staging)} ({largest.stat().st_size / 1024 / 1024:.2f} MiB)\n"
            f"사이트 파일 수: {len(files)}\n"
            "모든 사이트 파일이 파일당 25MB 제한 이내입니다.\n"
        )
        (staging / "UPLOAD.txt").write_text(report, encoding="utf-8")
        (staging / ".greenstoa-pages-build").write_text("Generated by scripts/build-cloudflare.py\n", encoding="utf-8")
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(staging, destination)
    print(report)
    print(f"Output: {destination}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist-cloudflare")
    build(parser.parse_args().output)
