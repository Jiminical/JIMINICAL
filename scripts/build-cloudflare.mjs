// Build the static site with Node alone for Cloudflare Workers Git builds.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.dirname(path.dirname(fileURLToPath(import.meta.url))),
  output=path.join(root,'dist-cloudflare'),marker='.greenstoa-pages-build',limit=25_000_000;
if(fs.existsSync(output)&&!fs.existsSync(path.join(output,marker)))
  throw new Error('Refusing to replace an output directory not marked as a Greenstoa build.');
const page=fs.readFileSync(path.join(root,'templates/index.html'),'utf8'),
  css=[...page.matchAll(/<link rel="stylesheet" href="(CSS\/[^\"]+)"/g)].map(match=>match[1]),
  scripts=[...page.matchAll(/<script src="(JS\/[^\"]+)"/g)].map(match=>match[1]);
if(!css.length||!scripts.length||page.includes('data:image/'))
  throw new Error('Expected the source template with separate game files.');
const staging=fs.mkdtempSync(path.join(os.tmpdir(),'greenstoa-cloudflare-'));
function files(directory){
  return fs.readdirSync(directory,{withFileTypes:true}).flatMap(entry=>{
    const file=path.join(directory,entry.name);return entry.isDirectory()?files(file):[file];
  });
}
try{
  fs.writeFileSync(path.join(staging,'index.html'),page);
  for(const name of [...css,...scripts]){
    const destination=path.join(staging,name);fs.mkdirSync(path.dirname(destination),{recursive:true});
    fs.copyFileSync(path.join(root,name),destination);
  }
  fs.cpSync(path.join(root,'assets'),path.join(staging,'assets'),{recursive:true});
  fs.writeFileSync(path.join(staging,'_headers'),'/*\n  X-Content-Type-Options: nosniff\n\n/index.html\n  Cache-Control: public, max-age=0, must-revalidate\n');
  fs.writeFileSync(path.join(staging,'.assetsignore'),marker+'\n');
  const entries=files(staging).map(file=>({file,size:fs.statSync(file).size}));
  for(const entry of entries)if(entry.size>=limit)
    throw new Error(`Asset exceeds 25 MB: ${path.relative(staging,entry.file)}`);
  const largest=entries.reduce((a,b)=>a.size>b.size?a:b);
  fs.writeFileSync(path.join(staging,marker),'Generated by npm run build\n');
  if(fs.existsSync(output))fs.rmSync(output,{recursive:true});
  fs.cpSync(staging,output,{recursive:true});
  console.log(`Built ${entries.length} static files in dist-cloudflare.`);
  console.log(`index.html: ${Buffer.byteLength(page).toLocaleString()} bytes.`);
  console.log(`Largest asset: ${path.relative(staging,largest.file)} (${(largest.size/1024/1024).toFixed(2)} MiB).`);
  console.log('All assets are below 25 MB; the portable root index.html is not deployed.');
}finally{
  fs.rmSync(staging,{recursive:true,force:true});
}
