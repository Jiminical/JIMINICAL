  function contains(poly, x, y) {
    let inside = false;
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [ax, ay] = poly[i],
        [bx, by] = poly[j];
      if (ay > y !== by > y && x < ((bx - ax) * (y - ay)) / (by - ay) + ax)
        inside = !inside;
    }
    return inside;
  }
  function point(key, x, y) {
    const map = maps[key];
    return Boolean(
      map &&
        map.floor.some((poly) => contains(poly, x, y)) &&
        !map.solids.some((poly) => contains(poly, x, y)),
    );
  }
